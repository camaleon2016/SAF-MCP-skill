/**
 * Coverage: for each technique, does this skill's static analysis cover it,
 * and if not, why not?
 *
 * Status is computed, not hand assigned:
 *   detected  a rule finds evidence or a risky configuration for it
 *   exposure  rules only report that the architecture has what it needs
 *   open      no rule yet, though upstream says it is observable in content
 *   runtime   no rule, and upstream says it is only observable outside static
 *             analysis (runtime, identity, network, model lifecycle, ...)
 *             (follow upstreamDetectionRule for upstream's runtime analytic)
 */
import { normalizeId, getTechnique, listTechniques, listTactics } from "./analyze.js";
import { listRules, type Basis } from "./rules.js";
import type { Technique } from "../types.js";

export type CoverageStatus = "detected" | "exposure" | "open" | "runtime";

export interface TechniqueCoverage {
  status: CoverageStatus | "deprecated";
  rules: Array<{ id: string; basis: Basis }>;
  modalities: string[];
  upstreamDetectionRule?: string | undefined;
  replacedBy?: string[] | undefined;
}

const STATIC_MODALITIES = new Set(["content", "static"]);

export function coverageFor(t: Technique): TechniqueCoverage {
  const rules = listRules()
    .filter((r) => r.techniqueId === t.id)
    .map((r) => ({ id: r.id, basis: r.basis }));
  const modalities = t.detectionModalities ?? [];
  const base = { rules, modalities, upstreamDetectionRule: t.upstreamDetectionRule };
  if (t.lifecycleStatus === "deprecated") return { ...base, status: "deprecated", replacedBy: t.replacedBy };
  let status: CoverageStatus;
  if (rules.some((r) => r.basis !== "exposure")) status = "detected";
  else if (rules.length) status = "exposure";
  else if (modalities.some((m) => STATIC_MODALITIES.has(m))) status = "open";
  else status = "runtime";
  return { ...base, status };
}

export function getTechniqueCoverage(id: string): TechniqueCoverage | undefined {
  const t = getTechnique(normalizeId(id));
  return t ? coverageFor(t) : undefined;
}

/** A technique with its coverage, as lookups return it. */
export function describeTechnique(id: string): (Technique & { coverage: TechniqueCoverage }) | undefined {
  const t = getTechnique(id);
  return t ? { ...t, coverage: coverageFor(t) } : undefined;
}

const activeTechniques = (): Technique[] => listTechniques().filter((t) => t.lifecycleStatus !== "deprecated");

export interface CoverageSummary {
  activeTechniques: number;
  rules: number;
  byStatus: Record<CoverageStatus, number>;
}

export function getCoverageSummary(): CoverageSummary {
  const byStatus: Record<CoverageStatus, number> = { detected: 0, exposure: 0, open: 0, runtime: 0 };
  const active = activeTechniques();
  for (const t of active) byStatus[coverageFor(t).status as CoverageStatus]++;
  return { activeTechniques: active.length, rules: listRules().length, byStatus };
}

/** docs/coverage.md, rendered from the rules and the synced catalog. Deterministic. */
export function renderCoverageMarkdown(upstreamCommit: string): string {
  const summary = getCoverageSummary();
  const tactics = listTactics();
  const short = upstreamCommit.slice(0, 7);
  const lines: string[] = [
    "# Coverage",
    "",
    `Generated by \`scripts/generate-coverage.ts\` from this skill's rules and the catalog synced from SAF-MCP commit \`${short}\`. Do not edit by hand; \`npm test\` fails if it is out of date.`,
    "",
    "For each active technique, this shows whether the skill's static analysis covers it, and if not, why not.",
    "",
    "| Status | Techniques | Meaning |",
    "|---|---|---|",
    `| detected | ${summary.byStatus.detected} | A rule finds evidence or a risky configuration |`,
    `| exposure | ${summary.byStatus.exposure} | Rules report that an architecture has what the attack needs, with no sign it is in use |`,
    `| open | ${summary.byStatus.open} | No rule yet, though upstream lists the technique as observable in content |`,
    `| runtime | ${summary.byStatus.runtime} | Only observable outside static analysis (at runtime, or through identity, network, or model lifecycle data); see upstream's detection rule |`,
    "",
    `${summary.rules} rules cover ${summary.byStatus.detected + summary.byStatus.exposure} of ${summary.activeTechniques} active techniques. Modalities come from upstream's detection registry. Upstream lists no analytics for the \`static\` modality, which is what this skill provides; this table can serve as the mapping document for registering it as an upstream provider.`,
    "",
  ];
  for (const tactic of tactics) {
    const ts = activeTechniques().filter((t) => t.tactic === tactic.id).sort((a, b) => a.id.localeCompare(b.id));
    if (ts.length === 0) continue;
    lines.push(`## ${tactic.name}`, "", "| Technique | Name | Status | Rules | Upstream modalities |", "|---|---|---|---|---|");
    for (const t of ts) {
      const c = coverageFor(t);
      const rules = c.rules.length ? c.rules.map((r) => `${r.id} (${r.basis})`).join(", ") : "";
      const status = c.status === "runtime" && c.upstreamDetectionRule ? `[runtime](${c.upstreamDetectionRule})` : c.status;
      lines.push(`| ${t.id} | ${t.name.replace(/\|/g, "\\|")} | ${status} | ${rules} | ${c.modalities.join(", ")} |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}
